export function makeClip(partial: Partial<Clip> & Pick<Clip, "id" | "trackId" | "kind" | "name" | "start" | "duration">): Clip {
  return {
    trimStart: 0,
    speed: 1,
    transform: { ...DEFAULT_TRANSFORM, ...(partial.transform ?? {}) },
    color: { ...DEFAULT_COLOR_GRADE, ...(partial.color ?? {}) },
    kenBurns: partial.kenBurns ?? "none",
    enterAnimation: partial.enterAnimation ?? "fade",
    exitAnimation: partial.exitAnimation ?? "none",
    animationDuration: partial.animationDuration ?? 0.5,
    loopAnimation: partial.loopAnimation ?? "none",
    transitionIn: partial.transitionIn ?? "none",
    transitionDuration: partial.transitionDuration ?? 0.45,
    ...partial,
  };
}

